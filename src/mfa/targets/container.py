"""Builds a container build context for any AgentSpec, laid out the way agents-cli expects.

    <out>/
      app/agent.py           root_agent = compiled graph   (generated shim)
      app/fast_api_app.py    app = FastAPI (A2A + /mfa/query) (generated shim)
      mfa/                   this framework
      agents/                your agents, copied unchanged
      requirements.txt       pinned to your local versions
      Dockerfile             uvicorn app.fast_api_app:app

The shims are generated, so the base application never needs an ``app/`` dir.
"""

from __future__ import annotations

import importlib.metadata as md
import shutil
from pathlib import Path

from mfa.runtime.models import parse_model
from mfa.spec import AgentSpec

REPO_ROOT = Path(__file__).resolve().parents[3]
MFA_SRC = REPO_ROOT / "src" / "mfa"
AGENTS_SRC = REPO_ROOT / "agents"

_BASE = ["langgraph", "langchain-core", "pydantic", "pyyaml", "fastapi", "uvicorn", "a2a-sdk"]
_PROVIDER = {
    "google_vertexai": ["langchain-google-vertexai"],
    "anthropic_vertex": ["langchain-google-vertexai", "anthropic"],
    "anthropic": ["langchain-anthropic", "anthropic"],
}

AGENT_SHIM = '''"""Generated by mfa: exports the agents-cli contract object. Do not edit; edit agents/ instead."""
from mfa.serving import load_root_agent

root_agent = load_root_agent()[2]
'''

APP_SHIM = '''"""Generated by mfa: the FastAPI app every container target runs. Do not edit."""
from mfa.serving.fast_api_app import app  # noqa: F401
'''

DOCKERFILE = """FROM python:{py}-slim
ENV PYTHONUNBUFFERED=1 PORT=8080 HOST=0.0.0.0
WORKDIR /code
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY mfa ./mfa
COPY agents ./agents
COPY app ./app
EXPOSE 8080
CMD ["sh", "-c", "uvicorn app.fast_api_app:app --host 0.0.0.0 --port ${{PORT}}"]
"""


def _pin(pkg: str, extra: str = "") -> str:
    try:
        return f"{pkg}{extra}=={md.version(pkg)}"
    except md.PackageNotFoundError:
        return f"{pkg}{extra}"


def container_requirements(spec: AgentSpec, model: str) -> list[str]:
    provider, _ = parse_model(model)
    pkgs = list(dict.fromkeys(_BASE + _PROVIDER.get(provider, [])))
    reqs = [_pin(p, "[http-server]" if p == "a2a-sdk" else "") for p in pkgs]
    return reqs + list(spec.requirements)


def build_context(spec: AgentSpec, model: str, out_dir: str | Path, python_version: str = "3.12") -> Path:
    out = Path(out_dir)
    if out.exists():
        shutil.rmtree(out)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "eval_results")
    shutil.copytree(MFA_SRC, out / "mfa", ignore=ignore)
    shutil.copytree(AGENTS_SRC, out / "agents", ignore=ignore)
    (out / "app").mkdir()
    (out / "app" / "__init__.py").write_text("")
    (out / "app" / "agent.py").write_text(AGENT_SHIM)
    (out / "app" / "fast_api_app.py").write_text(APP_SHIM)
    (out / "requirements.txt").write_text("\n".join(container_requirements(spec, model)) + "\n")
    (out / "Dockerfile").write_text(DOCKERFILE.format(py=python_version))
    (out / ".dockerignore").write_text("**/__pycache__\n**/*.pyc\n")
    return out
